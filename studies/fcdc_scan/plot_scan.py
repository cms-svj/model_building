# ---------------------------------------------------------------- Lund multiplicity vs kT threshold

def lund_kt(S, outdir):
    # shift of the mean primary Lund multiplicity vs kT threshold (rows: DP, reco; columns: Lambda and probVector scans per regime)
    scans = [(r'$\Lambda$, 2-body (ref. 0.6)', [(f'$m_\\pi/\\Lambda={r}$', S.get('fcdc', r), S.get('fcdc', 0.6)) for r in [0.3, 1.0, 1.4]]),
             (r'$\Lambda$, 3-body (ref. 1.7)', [(f'$m_\\pi/\\Lambda={r}$', S.get('fcdc', r), S.get('fcdc', 1.7)) for r in [1.6, 2.0, 2.5]]),
             (r'$p_V$, 2-body (ref. 0.333)', [(f'$p_V={pv}$', S.get('fcdc', 0.6, pv), S.get('fcdc', 0.6)) for pv in [0.1, 0.75]]),
             (r'$p_V$, 3-body (ref. 0.333)', [(f'$p_V={pv}$', S.get('fcdc', 1.7, pv), S.get('fcdc', 1.7)) for pv in [0.1, 0.75]])]
    fig, axes = plt.subplots(2, len(scans), figsize=(17, 8.5), sharex=True)
    rows = []
    for row, (pre, rlab) in enumerate([('DP', 'DP'), ('', 'Reco')]):
        for col, (title, ents) in enumerate(scans):
            ax = axes[row, col]
            for k, (lab, s, ref) in enumerate(ents):
                sh = [shift(s, ref, f'{pre}Jet12_lundMult{kt}') for kt in KTS]
                ax.errorbar(KTS, [a for a, _ in sh], yerr=[b for _, b in sh], color=style(k)['color'], marker=style(k)['marker'], linestyle=style(k)['linestyle'],
                            fillstyle='none', ms=8, capsize=3, linewidth=2, label=lab)
                rows += [shift_row(s, ref, f'Jet12_lundMult{kt}', rlab, v) for kt, v in zip(KTS, sh)]
            ax.axhline(0, color=MUTED, linewidth=1)
            ax.set_xscale('log'); ax.set_xticks(KTS, [str(kt) for kt in KTS])
            ax.tick_params(labelsize=15)
            if row == 0:
                ax.set_title(title, fontsize=18)
                ax.legend(fontsize=13, framealpha=0.5)
            else:
                ax.set_xlabel(r'Lund $k_T$ threshold [GeV]', fontsize=16)
        axes[row, 0].set_ylabel(f'{rlab}: Lund mult. shift [%]', fontsize=16)
    fig.tight_layout()
    save(fig, outdir, 'shift_vs_kt_threshold')
    write_csv(outdir, 'shifts', SHIFT_COLUMNS, rows)

# ---------------------------------------------------------------- per-sample summary table

def sample_summary(S, outdir):
    mean = lambda s, q: round(float(mean_err(s['hist'][q])[0]), 4)
    lund = [q for q in (f'{pre}Jet12_lundMult{kt}' for pre in ['DP', ''] for kt in KTS) if q not in SUBSTRUCTURE]
    columns = (['model', 'mpi_over_lambda', 'pvector', 'Lambda', 'mrho'] + SUBSTRUCTURE + EVENT + lund +
               ['rinv_per_jet', 'rinv_per_jet_stat_error', 'rinv_prediction', 'n_rho_3body', 'n_rho_SM', 'vector_fraction', 'jet_pt_reco_over_DH_visible'])
    rows = []
    for s in sorted(S.all, key=lambda s: (s['spec'], s['r'], s['pv'])):
        m = s['meta']
        rows.append([MODEL_LABEL[s['spec']], s['r'], s['pv'], round(m['scale'], 4), round(m['mrho'], 4)] +
                    [mean(s, q) for q in SUBSTRUCTURE + EVENT + lund] +
                    [round(float(rinv_mean(s)[0]), 4), round(float(rinv_mean(s)[1]), 4), round(float(m.get('rinvpred_3body', m.get('rinv_3body', 0.5))), 4),
                     mean(s, 'n_rho_3body'), mean(s, 'n_rho_SM'),
                     round(mean(s, 'n_rho')/(mean(s, 'n_rho') + mean(s, 'n_pion')), 3),
                     round(mean(s, 'Jet12_pt')/mean(s, 'DHVJet12_pt'), 3)])
    write_csv(outdir, 'sample_summary', columns, rows)

