# Plots and summary tables for the Lambda / probVector scan of the FCDC complete and simplified models.
# Each scan is shown at reco level (distributions) and along the dark jet chain
# (dark partons -> dark hadrons -> stable / visible descendants -> reco jets).
# Reads <samples>/s-channel*/{Hists,Meta}.pkl as written by run_model (see run_scan.sh).
