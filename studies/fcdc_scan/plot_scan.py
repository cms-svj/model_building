# repo plot style (font sizes and the accessible color/linestyle/marker cycle)
STYLES = list(set_plot_style())
MUTED = '#9c9ca1'
THRESHOLD = 1.52  # mpi/Lambda where mrho = 2 mpi in the Snowmass mass scheme: 2-body below, 3-body above
REF = {'2body': 0.6, '3body': 1.7}
RATIOS = {'2body': [0.3, 0.6, 1.0, 1.4], '3body': [1.6, 1.7, 2.0, 2.5]}
PV_REF = 0.333
MODEL_LABEL = {'fcdc': 'complete', 'fcdcSimp': 'simplified'}

SUBSTRUCTURE = ['Jet12_girth', 'Jet12_majoraxis', 'Jet12_minoraxis', 'Jet12_e2', 'Jet12_lundMult1']
EVENT = ['MET', 'MT', 'Dijet_mass', 'Jet12_pt', 'DeltaPhi_MET_Jet12']
ROW_TITLES = ['Jet substructure', 'Event level']
RINV = 'DHIVJet12_rinv_proj'
LUND_LABEL = r'Lund multiplicity ($k_T>1$ GeV)'

# dark jet chain: histogram prefix and label per level
LEVELS = [('DP', 'DP'), ('DH', 'DH'), ('DHIV', 'DH stable'), ('DHV', 'DH visible'), ('', 'Reco')]
CHAIN_QTY = [('pt', r'jet $p_T$'), ('nconst', r'$n_\mathrm{const}$'), ('girth', 'girth'), ('lundMult1', r'Lund mult. ($k_T>1$ GeV)')]
KTS = [1, 2, 5, 10]
SHIFT_COLUMNS = ['model', 'mpi_over_lambda', 'pvector', 'ref_model', 'ref_mpi_over_lambda', 'ref_pvector', 'variable', 'level', 'shift_percent', 'stat_error_percent']

# ---------------------------------------------------------------- samples

class Samples:
    def __init__(self, base):
        self.all = []
        for d in sorted(os.path.dirname(p) for p in glob.glob(f'{base}/s-channel*/Hists.pkl')):
            h = pickle.load(open(f'{d}/Hists.pkl', 'rb'))
            meta = pickle.load(open(f'{d}/Meta.pkl', 'rb'))
            m = h['model'] | meta | h['analysis']
            self.all.append(dict(r=round(m['mpi']/m['scale'], 2), pv=round(m['pvector'], 3), spec=m['spectrum'], hist=h['hist'], meta=m))
        # the scan generated by run_scan.sh: all mpi/Lambda points at the reference probVector, plus the probVector points at the two reference mpi/Lambda
        expected = [(spec, r, PV_REF) for spec in MODEL_LABEL for rs in RATIOS.values() for r in rs]
        expected += [(spec, r, pv) for spec in MODEL_LABEL for r in REF.values() for pv in [0.1, 0.2, 0.5, 0.75]]
        found = {(s['spec'], s['r'], s['pv']) for s in self.all}
        missing = [e for e in expected if e not in found]
        if missing:
            raise RuntimeError(f'{len(missing)} of {len(expected)} samples missing in {base}: ' +
                               ', '.join(f'{MODEL_LABEL[m]} mpi/Lambda={r} pV={pv}' for m, r, pv in missing))

    def get(self, spec, r, pv=PV_REF):
        return next(s for s in self.all if s['spec'] == spec and s['r'] == r and s['pv'] == pv)

    def select(self, spec, key, **fixed):
        # all samples of one model with the given fixed r and/or pv, sorted by key
        pts = [s for s in self.all if s['spec'] == spec and all(s[k] == v for k, v in fixed.items())]
        return sorted(pts, key=lambda s: s[key])

    def pvs(self, r):
        return sorted({s['pv'] for s in self.all if s['spec'] == 'fcdc' and s['r'] == r})

# ---------------------------------------------------------------- statistics

def xvals(h):
    # value per bin for means: counts filled into unit bins [n, n+1) (Lund multiplicity, hadron counts) are the integer n, not the bin center
    e = h.axes[0].edges
    if np.allclose(np.diff(e), 1) and np.allclose(e, np.round(e)):
        return e[:-1]
    return h.axes[0].centers

def mean_err(h):
    c = xvals(h); v = h.values(); n = v.sum()
    m = (c*v).sum()/n; sd = np.sqrt(((c-m)**2*v).sum()/n)
    return m, sd/np.sqrt(n)

def shift(s, ref, q):
    # relative shift of the mean of histogram q, in percent, with its statistical error
    m, e = mean_err(s['hist'][q]); m0, e0 = mean_err(ref['hist'][q])
    return 100*(m/m0 - 1), 100*np.hypot(e/m0, m*e0/m0**2)

def shift_row(s, ref, variable, level, sh):
    return [MODEL_LABEL[s['spec']], s['r'], s['pv'], MODEL_LABEL[ref['spec']], ref['r'], ref['pv'], variable, level, round(float(sh[0]), 2), round(float(sh[1]), 2)]

def rinv_mean(s):
    return s['meta'][RINV]['mean'], s['meta'][RINV]['stderr']

def norm(h):
    v = h.values(); var = h.variances() if h.variances() is not None else v
    t = v.sum()
    return v/t, np.sqrt(var)/t

# ---------------------------------------------------------------- output helpers

def save(fig, outdir, name, dpi=150):
    os.makedirs(outdir, exist_ok=True)
    for ext in ['png', 'pdf']:
        fig.savefig(f'{outdir}/{name}.{ext}', dpi=dpi, bbox_inches='tight')
    plt.close(fig)

def write_csv(outdir, name, columns, rows):
    os.makedirs(outdir, exist_ok=True)
    with open(f'{outdir}/{name}.csv', 'w', newline='') as f:
        w = csv.writer(f)
        w.writerow(columns)
        w.writerows(rows)

# ---------------------------------------------------------------- figure helpers

def xrange(hs, lo=0.002, hi=0.997):
    e = hs[0].axes[0].edges
    tot = sum(norm(h)[0] for h in hs); c = np.cumsum(tot)/tot.sum()
    i0 = max(np.searchsorted(c, lo) - 1, 0); i1 = min(np.searchsorted(c, hi) + 2, len(e)-1)
    return e[i0], e[i1]

def overlay(fig, spec_ax, entries, ref, q, ylabel=True):
    # entries: list of (label, hist, style index, is_ref); unit-normalized, log y, plus ratio to the reference
    gs = spec_ax.subgridspec(2, 1, height_ratios=[2.6, 1], hspace=0.07)
    ax = fig.add_subplot(gs[0]); rax = fig.add_subplot(gs[1], sharex=ax)
    href = entries[ref][1]; pr, er = norm(href); e = href.axes[0].edges
    for lab, h, k, isref in entries:
        st = STYLES[k]; col = st['color']
        hep.histplot(h, density=True, ax=ax, label=lab, flow='none', yerr=False, color=col, linestyle=st['linestyle'], linewidth=2)
        p, err = norm(h)
        with np.errstate(divide='ignore', invalid='ignore'):
            ratio = np.where(pr > 0, p/pr, np.nan); rerr = np.where(pr > 0, err/pr, np.nan)
        if isref:
            rax.fill_between(e[:-1], 1-rerr, 1+rerr, step='post', color=col, alpha=0.25, linewidth=0)
            rax.axhline(1, color=col, linewidth=1.5, linestyle=st['linestyle'])
        else:
            rax.stairs(ratio, e, color=col, linestyle=st['linestyle'], linewidth=2.0)
    x0, x1 = xrange([x[1] for x in entries]); ax.set_xlim(x0, x1)
    mask = (e[:-1] >= x0) & (e[1:] <= x1) & (pr > 0.01*pr.max())
    rvals = [norm(h)[0][mask]/pr[mask] for _, h, _, isref in entries if not isref]
    lo = min([np.nanmin(r) for r in rvals] + [0.8]); hi = max([np.nanmax(r) for r in rvals] + [1.2])
    rax.set_ylim(max(0, lo - 0.1), min(hi + 0.1, 3))
    ax.set_yscale('log'); ax.set_xlabel('')
    if ylabel:
        ax.set_ylabel('Arbitrary units'); rax.set_ylabel('ratio to ref.', fontsize=14)
    rax.set_xlabel(href.axes[0].label or q)
    rax.locator_params(axis='y', nbins=3); rax.locator_params(axis='x', nbins=4)
    plt.setp(ax.get_xticklabels(), visible=False)
    return ax

def grid_figure(rows, entries_fn, ref, outdir, name, row_titles, w=22, h=10.2):
    # rows: list of observable lists; entries_fn(q, row index) -> overlay entries
    fig = plt.figure(figsize=(w, h))
    gs = fig.add_gridspec(len(rows), max(len(r) for r in rows), wspace=0.32, hspace=0.42)
    first = None
    for i, qs in enumerate(rows):
        for j, q in enumerate(qs):
            ax = overlay(fig, gs[i, j], entries_fn(q, i), ref, q, ylabel=(j == 0))
            if j == 0:
                ax.set_title(row_titles[i], loc='left', fontsize=18, fontweight='bold', pad=10)
            first = first or ax
    hs, ls = first.get_legend_handles_labels()
    # anchor the legend just above the first row title (a fixed figure fraction leaves a gap in tall grids)
    fig.legend(hs, ls, loc='lower center', bbox_to_anchor=(0.5, fig.subplotpars.top + 0.55/h), ncol=len(hs), framealpha=0.5, handlelength=2.6)
    save(fig, outdir, name, dpi=100)

def scan_entries(S, spec, values, ref, key):
    # overlay entries for a Lambda (key 'r') or probVector (key 'pv') scan; the other parameter is fixed via ref = (r, pv)
    def fn(q, i):
        out = []
        for k, v in enumerate(values):
            s = S.get(spec, v, ref[1]) if key == 'r' else S.get(spec, ref[0], v)
            lab = (f'$m_\\pi/\\Lambda={v}$' if key == 'r' else f'$p_V={v}$') + (' (ref)' if v == ref[key == 'pv'] else '')
            out.append((lab, s['hist'][q], k, v == ref[key == 'pv']))
        return out
    return fn

def chain_figure(entries, outdir, name, ylabel, legend_title=None):
    # mean shift along the dark jet chain; entries: (label, sample, reference sample, style); returns the shifts as table rows
    fig, axes = plt.subplots(1, len(CHAIN_QTY), figsize=(17, 4.6))
    x = np.arange(len(LEVELS))
    rows = []
    for lab, s, ref, st in entries:
        for ax, (q, _) in zip(axes, CHAIN_QTY):
            sh = [shift(s, ref, f'{pre}Jet12_{q}') for pre, _ in LEVELS]
            ax.errorbar(x, [a for a, _ in sh], yerr=[b for _, b in sh], color=st['color'], marker=st['marker'], linestyle=st['linestyle'],
                        fillstyle='none', ms=8, capsize=3, linewidth=2, label=lab)
            rows += [shift_row(s, ref, f'Jet12_{q}', level, v) for (_, level), v in zip(LEVELS, sh)]
    for ax, (_, qlab) in zip(axes, CHAIN_QTY):
        ax.axhline(0, color=MUTED, linewidth=1)
        ax.set_title(qlab, fontsize=20)
        ax.set_xticks(x, [l for _, l in LEVELS], rotation=35, ha='right', fontsize=15)
        ax.tick_params(axis='y', labelsize=15)
    axes[0].set_ylabel(ylabel, fontsize=17)
    hs, ls = axes[0].get_legend_handles_labels()
    fig.tight_layout(w_pad=1.2, rect=(0, 0, 1, 0.86))
    fig.legend(hs, ls, loc='upper center', bbox_to_anchor=(0.5, 1.0), ncol=len(hs), framealpha=0.5, fontsize=16, title=legend_title)
    save(fig, outdir, name)
    return rows

def style(k):
    return STYLES[k % len(STYLES)]

# ---------------------------------------------------------------- Lambda scan

def lambda_scan(S, outdir):
    rows = []
    for regime, ratios in RATIOS.items():
        r = REF[regime]
        # reco-level distributions
        grid_figure([SUBSTRUCTURE, EVENT], scan_entries(S, 'fcdc', ratios, (r, PV_REF), 'r'), ratios.index(r), outdir, f'distributions_{regime}', ROW_TITLES)
        # along the dark jet chain
        others = [x for x in ratios if x != r]
        rows += chain_figure([(f'$m_\\pi/\\Lambda={x}$', S.get('fcdc', x), S.get('fcdc', r), style(k)) for k, x in enumerate(others)],
                             outdir, f'chain_{regime}', 'mean shift vs ref. [%]')
    write_csv(outdir, 'chain_shifts', SHIFT_COLUMNS, rows)

    # means vs mpi/Lambda across both regimes, complete and simplified
    fig, axes = plt.subplots(1, 4, figsize=(22, 5.4))
    for ax, q in zip(axes, ['Jet12_lundMult1', 'Jet12_girth', 'MT', RINV]):
        for k, (spec, lab) in enumerate([('fcdc', 'FCDC (complete)'), ('fcdcSimp', 'simplified')]):
            st = STYLES[k]
            pts = S.select(spec, 'r', pv=PV_REF)
            ms = [rinv_mean(s) if q == RINV else mean_err(s['hist'][q]) for s in pts]
            ax.plot([s['r'] for s in pts], [m for m, _ in ms], label=lab, fillstyle='none', ms=8, **st)
            ax.errorbar([s['r'] for s in pts], [m for m, _ in ms], yerr=[e for _, e in ms], fmt='none', ecolor=st['color'], capsize=3)
        ax.axvline(THRESHOLD, color=MUTED, linestyle='--', linewidth=1.5, label='2-body | 3-body threshold')
        ax.set_xlabel(r'$m_\pi/\Lambda$')
        ax.set_ylabel('mean ' + (LUND_LABEL if q == 'Jet12_lundMult1' else (S.all[0]['hist'][q].axes[0].label or q)))
    hs, ls = axes[0].get_legend_handles_labels()
    fig.tight_layout(w_pad=2.5)
    fig.legend(hs, ls, loc='lower center', bbox_to_anchor=(0.5, 0.98), ncol=3, framealpha=0.5)
    save(fig, outdir, 'means_vs_mpi_over_lambda', dpi=100)

    # per-jet rinv vs mpi/Lambda, generated vs prediction (0.5 in 2-body, effective-rinv formula in 3-body)
    fig, ax = plt.subplots(figsize=(10, 7))
    k = 0
    for reg, below in [('2-body', True), ('3-body', False)]:
        for spec, lab, pk in [('fcdc', 'FCDC', 'rinvpred_3body'), ('fcdcSimp', 'simplified', 'rinv_3body')]:
            st = STYLES[k]; k += 1
            pts = [s for s in S.select(spec, 'r', pv=PV_REF) if (s['r'] < THRESHOLD) == below]
            xs = [s['r'] for s in pts]
            ax.errorbar(xs, [rinv_mean(s)[0] for s in pts], yerr=[rinv_mean(s)[1] for s in pts],
                        fmt=st['marker'], fillstyle='none', ms=9, color=st['color'], capsize=3, linestyle='none', label=f'{lab}, {reg}: generated')
            ax.plot(xs, [s['meta'].get(pk, 0.5) for s in pts], linestyle=st['linestyle'], color=st['color'], linewidth=1.5, label=f'{lab}, {reg}: prediction')
    ax.axvline(THRESHOLD, color=MUTED, linestyle='--', linewidth=1.5)
    ax.set_xlabel(r'$m_\pi/\Lambda$  ($p_V=0.333$)'); ax.set_ylabel('mean ' + S.all[0]['hist'][RINV].axes[0].label)
    ax.legend(framealpha=0.5, fontsize=12, loc='lower left', ncol=2)
    ax.set_ylim(0.3, 0.52)
    save(fig, outdir, 'rinv_vs_mpi_over_lambda')

# ---------------------------------------------------------------- probVector scan

def probvector_scan(S, outdir):
    rows = []
    for regime in RATIOS:
        r = REF[regime]; pvs = S.pvs(r)
        # reco-level distributions
        grid_figure([SUBSTRUCTURE, EVENT], scan_entries(S, 'fcdc', pvs, (r, PV_REF), 'pv'), pvs.index(PV_REF), outdir, f'distributions_{regime}', ROW_TITLES)
        # along the dark jet chain: mean shifts, and the distributions per collection
        rows += chain_figure([(f'$p_V={pv}$', S.get('fcdc', r, pv), S.get('fcdc', r), style(k)) for k, pv in enumerate(x for x in pvs if x != PV_REF)],
                             outdir, f'chain_{regime}', 'mean shift vs ref. [%]')
        collections = [[f'{pre}Jet12_{v}' for v in ['nconst', 'girth', 'lundMult1']] for pre in ['DP', 'DH', 'DHV', '']]
        grid_figure(collections, scan_entries(S, 'fcdc', pvs, (r, PV_REF), 'pv'), pvs.index(PV_REF), outdir, f'collections_{regime}',
                    ['Dark partons', 'Dark hadrons', 'DH visible', 'Reco'], w=15, h=19)
    write_csv(outdir, 'chain_shifts', SHIFT_COLUMNS, rows)

    # per-jet rinv vs probVector in both regimes, generated vs prediction (0.5 in 2-body, effective-rinv formula in 3-body)
